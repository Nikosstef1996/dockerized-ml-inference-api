"""Inference wrapper for a trusted, locally trained scikit-learn artifact."""
from functools import lru_cache
from pathlib import Path

import joblib
import pandas as pd

from app.features import next_day_features

ROOT = Path(__file__).resolve().parent.parent
MODEL_PATH = ROOT / "models" / "day_ahead_rf.joblib"


@lru_cache(maxsize=4)
def _load_model(model_path: str):
    """Load once per process; restart the service after updating the model."""
    return joblib.load(model_path)


def forecast_model(last_168_hours_mwh: list[float], forecast_start_utc: pd.Timestamp,
                   model_path: Path = MODEL_PATH) -> list[float]:
    """Predict using only an artifact generated by our own training pipeline.

    Never download and load arbitrary pickle/joblib files from untrusted sources.
    """
    model = _load_model(str(model_path))
    features = next_day_features(last_168_hours_mwh, forecast_start_utc)
    prediction = model.predict(features)
    return [float(max(0, v)) for v in prediction]
